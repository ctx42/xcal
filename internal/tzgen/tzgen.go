// Package tzgen generates the Go source of the xcal timezone tables from a
// JSON file.
package tzgen

import (
	"bytes"
	"cmp"
	"encoding/json"
	"fmt"
	goformat "go/format"
	"os"
	"slices"
	"strings"

	"github.com/ctx42/xcal/pkg/xcal"
)

// GenerateTZ generates a Go source file at dst from the src JSON file, with
// the given package name.
func GenerateTZ(src, dst, name string) error {
	zs, err := ReadZones(src)
	if err != nil {
		return err
	}

	return GenerateTZGo(zs, dst, name)
}

// ReadZones reads a timezones JSON file and returns a slice of validated
// Zone instances.
func ReadZones(pth string) ([]*xcal.Zone, error) {
	data, err := os.ReadFile(pth)
	if err != nil {
		return nil, err
	}

	var zs []*xcal.Zone
	if err = json.Unmarshal(data, &zs); err != nil {
		return nil, err
	}

	seenIDs := make(map[int]bool, len(zs))
	seenNames := make(map[string]bool, len(zs))
	for i, zon := range zs {
		if err = zon.Check(); err != nil {
			return nil, fmt.Errorf("at index %d: %w", i, err)
		}
		if seenNames[zon.Name] {
			format := "at index %d: duplicate timezone %s"
			return nil, fmt.Errorf(format, i, zon.Name)
		}
		if seenIDs[zon.Id] {
			format := "at index %d: duplicate ZoneID %d"
			return nil, fmt.Errorf(format, i, zon.Id)
		}
		seenIDs[zon.Id] = true
		seenNames[zon.Name] = true
		if len(xcal.Zones) > 0 {
			if have, ok := xcal.Zones[zon.Name]; ok && have.Id != zon.Id {
				format := "at index %d: expected ZoneID %d got %d"
				return nil, fmt.Errorf(format, i, have.Id, zon.Id)
			}
		} else if zon.Id != i {
			format := "at index %d: expected ZoneID %d got %d"
			return nil, fmt.Errorf(format, i, i, zon.Id)
		}
	}
	return zs, nil
}

// GenerateTZGo generates a Go source file with timezones. The map entries are
// sorted by key, so the output is the same for the same input.
func GenerateTZGo(zs []*xcal.Zone, dst, name string) error {
	byName := slices.SortedFunc(slices.Values(zs), func(a, b *xcal.Zone) int {
		return strings.Compare(a.Name, b.Name)
	})
	byID := slices.SortedFunc(slices.Values(zs), func(a, b *xcal.Zone) int {
		return cmp.Compare(a.Id, b.Id)
	})

	var buf bytes.Buffer
	header := "" +
		"// Code generated by xcal/pkg/xcal. DO NOT EDIT.\n\n" +
		"package %s\n\n" +
		"// Zones maps timezone names to Zone instances.\n" +
		"var Zones = map[string]*Zone{\n"
	_, _ = fmt.Fprintf(&buf, header, name)
	for _, zon := range byName {
		_, _ = fmt.Fprintf(&buf, "%q: %s,\n", zon.Name, zoneLit(zon))
	}

	middle := "" +
		"}\n\n" +
		"// ZoneIDs maps timezone IDs to Zone instances.\n" +
		"var ZoneIDs = map[int]*Zone{\n"
	_, _ = fmt.Fprint(&buf, middle)
	for _, zon := range byID {
		_, _ = fmt.Fprintf(&buf, "%d: %s,\n", zon.Id, zoneLit(zon))
	}
	_, _ = fmt.Fprint(&buf, "}\n")

	src, err := goformat.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated code: %w", err)
	}
	return os.WriteFile(dst, src, 0644)
}

// zoneLit returns the zone as a Go composite literal with the type elided.
func zoneLit(zon *xcal.Zone) string {
	format := "" +
		"{\n" +
		"Id: %d,\n" +
		"Name: %q,\n" +
		"Status: %q,\n" +
		"Offset: %d,\n" +
		"OffsetDST: %d,\n" +
		"Link: %q,\n" +
		"Notes: %q,\n" +
		"CountryCode: %q,\n" +
		"}"
	return fmt.Sprintf(
		format,
		zon.Id,
		zon.Name,
		zon.Status,
		zon.Offset,
		zon.OffsetDST,
		zon.Link,
		zon.Notes,
		zon.CountryCode,
	)
}
